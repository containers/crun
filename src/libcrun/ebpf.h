#ifndef EBPF_H
#define EBPF_H

#include <config.h>
#include <stdio.h>
#include <stdlib.h>
#include "error.h"
#include <errno.h>
#include <argp.h>
#include <ocispec/runtime_spec_schema_config_schema.h>
#include "container.h"

#define SYS_FS_BPF "/sys/fs/bpf"
#define CRUN_BPF_DIR SYS_FS_BPF "/crun"

struct bpf_program;

struct bpf_program *bpf_program_new (size_t size);
struct bpf_program *bpf_program_append (struct bpf_program *p, void *data, size_t size);

struct bpf_program *bpf_program_init_dev (struct bpf_program *program, libcrun_error_t *err);
struct bpf_program *bpf_program_append_dev (struct bpf_program *program, const char *access, char type, int major,
                                            int minor, bool accept, libcrun_error_t *err);
struct bpf_program *bpf_program_complete_dev (struct bpf_program *program, libcrun_error_t *err);

int libcrun_ebpf_load (struct bpf_program *program, int dirfd, const char *pin, libcrun_error_t *err);
int libcrun_ebpf_read_program (struct bpf_program **program, const char *path, libcrun_error_t *err);
int libcrun_ebpf_query_cgroup_progs (const char *cgroup_path, uint32_t **progs_out, size_t *n_progs_out, libcrun_error_t *err);
bool libcrun_ebpf_cmp_programs (struct bpf_program *program1, struct bpf_program *program2);

#define CRUN_DEV_MAX_RULES 1024

/* The device filter reads its rules from a map that has a separate value for each cgroup it is attached to.  A function
   returns 1 if the filter is not available, the caller should then use the filter generated by create_dev_bpf.  A list
   of more than CRUN_DEV_MAX_RULES rules, including the default devices, is an error.  */

/* Attach the filter to the cgroup, or replace its rules if it is already attached.  Return 1 if it cannot be attached,
   e.g. another program is attached to the cgroup.  On an error the previous filter of the cgroup is kept.  */
int libcrun_ebpf_devices_set (runtime_spec_schema_defs_linux_device_cgroup **devs, size_t devs_len, int cgroup_fd,
                              libcrun_error_t *err);

/* Replace the rules of the filter that is already attached to the cgroup.  Return 1 if there is no such filter.  */
int libcrun_ebpf_devices_update (runtime_spec_schema_defs_linux_device_cgroup **devs, size_t devs_len, int cgroup_fd,
                                 libcrun_error_t *err);

/* Insert each rule of DEVS in front of the rules of the user of the filter that is already attached to the cgroup, so
   that the last one has the highest priority.  The current rules are read back from the map, and the default devices
   are kept first.  A rule that is already present is moved instead of being added again.  Return 1 if there is no such
   filter.  The caller must prevent concurrent changes to the rules of the cgroup.  */
int libcrun_ebpf_devices_add (runtime_spec_schema_defs_linux_device_cgroup **devs, size_t devs_len, int cgroup_fd,
                              libcrun_error_t *err);

/* Pin the filter, if it is not already, and return its path in PATH.  The program is the same for every container, and
   it must not be removed.  */
int libcrun_ebpf_devices_pin (runtime_spec_schema_defs_linux_device_cgroup **devs, size_t devs_len, char **path,
                              libcrun_error_t *err);

#endif
